export const LANGS = {ru:'RU', kk:'KZ', en:'EN'};
let lang = 'ru';
try{ const l = localStorage.getItem('lang'); if(l in DICT) lang = l; }catch{}
const listeners = [];

export const getLang = () => lang;

export function t(key, vars){
  let s = DICT[lang][key] ?? DICT.ru[key] ?? key;
  if(vars) s = s.replace(/\{(\w+)\}/g, (m,k) => k in vars ? vars[k] : m);
  return s;
}

/* Title of a criterion in the current language (custom or edited titles are shown as written) */
export function criterionTitle(c){
  const id = c.id ?? c.criterion_id, tr = CRITERION_TITLES[id];
  return tr && c.title===tr.ru ? tr[lang] : c.title;
}

export function applyI18n(root = document){
  root.querySelectorAll('[data-i18n]').forEach(el => el.textContent = t(el.dataset.i18n));
  root.querySelectorAll('[data-i18n-title]').forEach(el => el.title = t(el.dataset.i18nTitle));
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => el.placeholder = t(el.dataset.i18nPlaceholder));
  document.documentElement.lang = lang==='kk' ? 'kk' : lang;
  document.title = t('app.title');
}

export function setLang(l){
  if(!(l in DICT) || l===lang) return;
  lang = l;
  try{ localStorage.setItem('lang', l); }catch{}
  applyI18n();
  listeners.forEach(fn => fn());
}

/* Re-render dynamic parts when the language changes */
export const onLangChange = fn => listeners.push(fn);
